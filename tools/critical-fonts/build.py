#!/usr/bin/env python3
"""PF-57: inline a tiny subset of each design face for the first screen.

Why: the web fonts use font-display: swap and take ~1 s on Slow 4G, so the header and Hello copy
first painted in the local fallbacks and then visibly changed typeface. These subsets hold only
the glyphs the first screen uses (tools/critical-fonts/chars.json, from collect.mjs), cut from the
same @fontsource / repo woff2 files, and are inlined as data: URLs in the page's CSS, so the first
text frame is already in the final face. They sit right after each web font in the font stacks
(tokens.css): the full file still loads and takes over with identical glyphs and metrics.

Needs fontTools and brotli. Regenerate after the header or Hello copy changes:

    python3 tools/critical-fonts/build.py
"""

from __future__ import annotations

import base64
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FS = ROOT / "node_modules/@fontsource"
OUT = ROOT / "src/app/styles/fonts-critical.css"
CHARS = json.loads((Path(__file__).parent / "chars.json").read_text(encoding="utf-8"))

# (family, weight, style, source file, keys of chars.json it renders)
FACES = [
    ("Be Vietnam Pro Critical", 400, "normal",
     FS / "be-vietnam-pro/files/be-vietnam-pro-latin-400-normal.woff2",
     # 500 has no web face: it is matched to the 400 file.
     ["Be Vietnam Pro|400|normal", "Be Vietnam Pro|500|normal"]),
    ("Be Vietnam Pro Critical", 600, "normal",
     FS / "be-vietnam-pro/files/be-vietnam-pro-latin-600-normal.woff2",
     ["Be Vietnam Pro|600|normal"]),
    ("Instrument Serif Critical", 400, "normal",
     ROOT / "src/app/fonts/instrument-serif-400.woff2", ["Instrument Serif|400|normal"]),
    ("Instrument Serif Critical", 400, "italic",
     ROOT / "src/app/fonts/instrument-serif-400-italic.woff2", ["Instrument Serif|400|italic"]),
    ("IBM Plex Mono Critical", 400, "normal",
     FS / "ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff2", ["IBM Plex Mono|400|normal"]),
    ("IBM Plex Mono Critical", 500, "normal",
     FS / "ibm-plex-mono/files/ibm-plex-mono-latin-500-normal.woff2", ["IBM Plex Mono|500|normal"]),
]


def cut(src: Path, chars: str) -> bytes:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]
    # Hinting kept: with full hinting (some Linux fontconfig setups) the hinted advances of the
    # full files would otherwise differ from the subset by up to 1 px a word.
    options.hinting = True
    options.name_IDs = [1, 2]
    options.notdef_outline = False
    font = TTFont(src)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=chars)
    subsetter.subset(font)
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    return out.getvalue()


def main() -> None:
    blocks = []
    total = 0
    for family, weight, style, src, keys in FACES:
        chars = "".join(sorted(set("".join(CHARS.get(key, "") for key in keys))))
        data = cut(src, chars)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        blocks.append(
            "@font-face {\n"
            f'  font-family: "{family}";\n'
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: block;\n"
            f'  src: url("data:font/woff2;base64,{b64}") format("woff2");\n'
            "}\n"
        )
        print(f"{family} {weight} {style}: {len(chars)} chars, {len(data)} B")
    header = (
        "/* GENERATED by tools/critical-fonts/build.py from tools/critical-fonts/chars.json; do not\n"
        "   edit. PF-57: the first screen's glyphs of each design face, inlined so the first text\n"
        "   frame is already in the final typeface (the full files still load and take over).\n"
        f"   {total} B of woff2 in total. block: these are data: URLs, ready within a frame. */\n"
    )
    OUT.write_text(header + "\n".join(blocks), encoding="utf-8")
    print(f"total {total} B -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
